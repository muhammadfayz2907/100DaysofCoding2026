public class Day69 {
    public static void main(String[] args) {

        int a = 6;
      
        int b = 7; 

        for (int i = 1; i <= a; i++) {
            for (int j = 1; j <= b; j++) {
                System.out.print("* ");
            }
            System.out.println();
        }
    }
}
